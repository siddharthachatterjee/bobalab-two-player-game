// Regenerates everything derived from the arm CSVs in shared/arms/.
// Run after replacing the CSVs:   node scripts/build-arms.mjs
//
//   shared/arms/tables.js      the CSV text as a JS module, so the browser builds
//                              and the Empirica server can import it without fs
//   .empirica/treatments.yaml  one Empirica treatment per arm in shared/arms/active.js
import { readFileSync, writeFileSync } from "node:fs";
import { ACTIVE_BLOCKS } from "../shared/arms/active.js";

const root = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");
const FILES = {
  arms: "arms.csv",
  targets: "targets.csv",
  messageRules: "message_rules.csv",
  forwardingRules: "forwarding_rules.csv",
  opponentShipments: "opponent_shipments.csv",
};

// ---------------------------------------------------------------- tables.js
const csv = Object.fromEntries(Object.entries(FILES).map(([k, f]) => [k, read(`shared/arms/${f}`)]));
writeFileSync(
  new URL("shared/arms/tables.js", root),
  `// GENERATED by scripts/build-arms.mjs from the CSVs in this folder. Do not edit.\n` +
    `export const CSV = ${JSON.stringify(csv, null, 2)};\n`,
);

// ---------------------------------------------------------------- treatments.yaml
const arms = csv.arms
  .trim()
  .split(/\r?\n/)
  .slice(1)
  .map((line) => line.split(","))
  .filter((cells) => ACTIVE_BLOCKS.includes(cells[1]))
  .map((cells) => cells[0]);
const label = (id) => {
  const [block, forwarding, r] = id.split("_");
  return `${block} · ${forwarding} · suggestion ${r === "R1" ? "on" : "off"}`;
};
const yaml = [
  "# GENERATED by scripts/build-arms.mjs from shared/arms/arms.csv. Do not edit.",
  "# One treatment per arm in shared/arms/active.js. The arm_id selects every rule; see shared/arms/SPEC.md.",
  "factors:",
  "  - desc: Number of players in a game.",
  "    name: playerCount",
  "    values:",
  "      - value: 2",
  "  - desc: Row of shared/arms/arms.csv (block, forwarding, AI suggestion).",
  "    name: arm",
  "    values:",
  ...arms.map((id) => `      - value: ${id}`),
  "treatments:",
  ...arms.flatMap((id) => [`  - name: "${label(id)}"`, `    factors: { playerCount: 2, arm: ${id} }`]),
  "",
].join("\n");
writeFileSync(new URL(".empirica/treatments.yaml", root), yaml);

console.log(`Wrote shared/arms/tables.js and .empirica/treatments.yaml (${arms.length} arms).`);
